// Package gotestconfig exposes the canonical `go test` and coverage
// configuration shared by the teo-garcia Go templates.
//
// `go test` has no config file and no way to exclude files from a coverage
// profile, and the toolchain emits neither LCOV nor a threshold check. This
// package supplies all four on top of the standard profile format.
package gotestconfig

import (
	"bytes"
	_ "embed"
	"fmt"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

//go:embed gotest.yml
var baseline []byte

// Config is the decoded shared configuration.
type Config struct {
	Version  string         `yaml:"version"`
	Test     TestConfig     `yaml:"test"`
	Coverage CoverageConfig `yaml:"coverage"`
}

// TestConfig controls how `go test` is invoked.
type TestConfig struct {
	Race     bool   `yaml:"race"`
	Shuffle  string `yaml:"shuffle"`
	Timeout  string `yaml:"timeout"`
	Verbose  bool   `yaml:"verbose"`
	Packages string `yaml:"packages"`
}

// CoverageConfig controls profile collection and reporting.
type CoverageConfig struct {
	CoverMode string   `yaml:"covermode"`
	CoverPkg  string   `yaml:"coverpkg"`
	Dir       string   `yaml:"dir"`
	Profile   string   `yaml:"profile"`
	Reporters []string `yaml:"reporters"`
	LCOV      string   `yaml:"lcov"`
	HTML      string   `yaml:"html"`
	Threshold float64  `yaml:"threshold"`
	Exclude   []string `yaml:"exclude"`
}

// Baseline returns the canonical configuration as raw YAML.
//
// The returned slice is a copy; mutating it does not affect later calls.
func Baseline() []byte {
	out := make([]byte, len(baseline))
	copy(out, baseline)
	return out
}

// Load parses the shared baseline with an optional overlay merged on top.
func Load(overlay []byte) (Config, error) {
	merged, err := Merge(overlay)
	if err != nil {
		return Config{}, err
	}
	var cfg Config
	if err := yaml.Unmarshal(merged, &cfg); err != nil {
		return Config{}, fmt.Errorf("decode merged config: %w", err)
	}
	return cfg, nil
}

// Merge deep-merges overlay onto the shared baseline and returns the result as
// YAML.
//
// Maps merge key by key at every depth. Scalars and sequences are replaced
// wholesale, so a consumer can shrink `coverage.exclude`, not only grow it.
func Merge(overlay []byte) ([]byte, error) {
	base := map[string]any{}
	if err := yaml.Unmarshal(baseline, &base); err != nil {
		return nil, fmt.Errorf("parse baseline config: %w", err)
	}

	if len(bytes.TrimSpace(overlay)) > 0 {
		over := map[string]any{}
		if err := yaml.Unmarshal(overlay, &over); err != nil {
			return nil, fmt.Errorf("parse overlay config: %w", err)
		}
		base = mergeMaps(base, over)
	}

	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(base); err != nil {
		return nil, fmt.Errorf("encode merged config: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("encode merged config: %w", err)
	}

	header := "# Generated by gotest-config-shared. Do not edit; edit the overlay instead.\n"
	return append([]byte(header), buf.Bytes()...), nil
}

// Write merges overlay onto the baseline and writes the result to path.
func Write(path string, overlay []byte) error {
	merged, err := Merge(overlay)
	if err != nil {
		return err
	}
	if dir := filepath.Dir(path); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return fmt.Errorf("create config directory %s: %w", dir, err)
		}
	}
	if err := os.WriteFile(path, merged, 0o600); err != nil {
		return fmt.Errorf("write config to %s: %w", path, err)
	}
	return nil
}

// TestArgs renders the canonical `go test` flags implied by the config.
//
// The result is meant to be interpolated into a Makefile recipe, which is why
// it is a flag list rather than an exec call.
func (c Config) TestArgs() []string {
	args := make([]string, 0, 8)
	if c.Test.Verbose {
		args = append(args, "-v")
	}
	if c.Test.Race {
		args = append(args, "-race")
	}
	if c.Test.Shuffle != "" {
		args = append(args, "-shuffle="+c.Test.Shuffle)
	}
	if c.Test.Timeout != "" {
		args = append(args, "-timeout="+c.Test.Timeout)
	}
	if c.Coverage.CoverMode != "" {
		args = append(args, "-covermode="+c.Coverage.CoverMode)
	}
	if c.Coverage.CoverPkg != "" {
		args = append(args, "-coverpkg="+c.Coverage.CoverPkg)
	}
	if c.Coverage.Profile != "" {
		args = append(args, "-coverprofile="+c.Coverage.Profile)
	}
	if c.Test.Packages != "" {
		args = append(args, c.Test.Packages)
	}
	return args
}

// Validate reports configuration that would silently produce wrong numbers.
func (c Config) Validate() error {
	// -race requires atomic counters; set/count undercount concurrent hits and
	// would report a coverage number that is quietly too low.
	if c.Test.Race && c.Coverage.CoverMode != "atomic" {
		return fmt.Errorf("covermode %q is unsafe with race enabled; use atomic", c.Coverage.CoverMode)
	}
	known := map[string]bool{"text": true, "lcov": true, "html": true}
	for _, r := range c.Coverage.Reporters {
		if !known[r] {
			return fmt.Errorf("unknown coverage reporter %q; want text, lcov, or html", r)
		}
	}
	if c.Coverage.Threshold < 0 || c.Coverage.Threshold > 100 {
		return fmt.Errorf("coverage threshold %v is outside 0-100", c.Coverage.Threshold)
	}
	return nil
}

func mergeMaps(base, overlay map[string]any) map[string]any {
	out := make(map[string]any, len(base)+len(overlay))
	for k, v := range base {
		out[k] = v
	}
	for k, ov := range overlay {
		bv, exists := out[k]
		if !exists {
			out[k] = ov
			continue
		}
		bm, baseIsMap := bv.(map[string]any)
		om, overlayIsMap := ov.(map[string]any)
		if baseIsMap && overlayIsMap {
			out[k] = mergeMaps(bm, om)
			continue
		}
		out[k] = ov
	}
	return out
}
